#Modules

'''Modules are python files which are written by another developer.for example-math,random,datetime etc.we can use these modules by importing them & use their functions or attributes'''

import math,random,datetime
print(math.sqrt(16))
print(random.randint(1,100))
print(datetime.datetime.now())

'''.sqrt() is the attribute of math module,.randint() is for random &.datetime.now() is for datetime module.'''